export function translate(lang, key, vars) {
  // "{key}.one" holds the singular form, used when vars.n === 1.
  const entry = (vars && vars.n === 1 && D[`${key}.one`]) || D[key];
  let s = entry ? entry[lang === 'hi' ? 1 : 0] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Adds entries (used by screens that keep their own text next to them). */
export function extend(entries) { Object.assign(D, entries); }

/** t(key, vars) in the current app language, plus `lang`. Re-renders when the language changes. */
export function useT() {
  const { prefs } = usePrefs();
  const lang = prefs.lang === 'hi' ? 'hi' : 'en';
  const t = useCallback((key, vars) => translate(lang, key, vars), [lang]);
  return { t, lang };
}

/** Outside React (e.g. alerts in callbacks). */
export const tNow = (key, vars) => translate(getApiLang(), key, vars);

/**
 * A user-facing message for an error: known codes are translated; others use the
 * server's message (English).
 */
export function errorText(err, t) {
  if (!err) return '';
  if (err.status === 0 || err.code === 'network') return t('errors.network');
  if (err.code === 'premium_required' && err.details?.feature) {
    return t(`premium.feature.${err.details.feature}`, { days: err.details.days ?? 30, n: err.details.bookmarks ?? 20 });
  }
  if (err.code === 'guest_limit') return t('errors.guestLimit', { n: 20 });
  if (err.code === 'email_not_verified') return t('errors.emailNotVerified');
  return err.message || t('common.pleaseTryAgain');
}
